-- Лабораторна робота №2: інтернет-магазин електроніки
-- Запускати у PostgreSQL. Скрипт повторно створює лише схему electronics_store.

BEGIN;

DROP SCHEMA IF EXISTS electronics_store CASCADE;
CREATE SCHEMA electronics_store;
SET LOCAL search_path TO electronics_store, public;

-- 1. Облікові записи покупців і працівників
CREATE TABLE accounts (
    account_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(120) NOT NULL,
    email          VARCHAR(254) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL CHECK (length(trim(password_hash)) > 0),
    role           VARCHAR(20) NOT NULL CHECK (role IN ('buyer', 'staff'))
);

-- 2. Категорії товарів
CREATE TABLE categories (
    category_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80) NOT NULL UNIQUE
);

-- 3. Каталог товарів
CREATE TABLE products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     INTEGER NOT NULL,
    name            VARCHAR(160) NOT NULL,
    brand           VARCHAR(80) NOT NULL,
    model           VARCHAR(80) NOT NULL,
    price           NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    stock_quantity  INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories (category_id)
        ON DELETE RESTRICT
);

-- 4. Набір характеристик, спільний для товарів категорії
CREATE TABLE characteristics (
    characteristic_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id        INTEGER NOT NULL,
    name               VARCHAR(80) NOT NULL,
    value_type         VARCHAR(20) NOT NULL CHECK (value_type IN ('text', 'number', 'boolean')),
    unit               VARCHAR(20),
    CONSTRAINT uq_characteristics_category_name UNIQUE (category_id, name),
    CONSTRAINT fk_characteristics_category
        FOREIGN KEY (category_id) REFERENCES categories (category_id)
        ON DELETE RESTRICT
);

-- 5. Значення характеристики для товару (асоціативна таблиця)
CREATE TABLE product_characteristics (
    product_id         INTEGER NOT NULL,
    characteristic_id  INTEGER NOT NULL,
    value              VARCHAR(255) NOT NULL,
    CONSTRAINT pk_product_characteristics PRIMARY KEY (product_id, characteristic_id),
    CONSTRAINT fk_product_characteristics_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_product_characteristics_characteristic
        FOREIGN KEY (characteristic_id) REFERENCES characteristics (characteristic_id)
        ON DELETE CASCADE
);

-- 6. Один активний кошик на акаунт покупця
CREATE TABLE carts (
    cart_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  INTEGER NOT NULL UNIQUE,
    CONSTRAINT fk_carts_account
        FOREIGN KEY (account_id) REFERENCES accounts (account_id)
        ON DELETE CASCADE
);

-- 7. Товари та їх кількість у кошику
CREATE TABLE cart_items (
    cart_id     INTEGER NOT NULL,
    product_id  INTEGER NOT NULL,
    quantity    INTEGER NOT NULL CHECK (quantity > 0),
    CONSTRAINT pk_cart_items PRIMARY KEY (cart_id, product_id),
    CONSTRAINT fk_cart_items_cart
        FOREIGN KEY (cart_id) REFERENCES carts (cart_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON DELETE RESTRICT
);

-- 8. Замовлення покупців
CREATE TABLE customer_orders (
    order_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        INTEGER NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status            VARCHAR(20) NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'paid', 'shipped', 'delivered', 'cancelled')),
    payment_method    VARCHAR(30) NOT NULL
        CHECK (payment_method IN ('card_online', 'cash_on_delivery')),
    recipient_name    VARCHAR(120) NOT NULL,
    recipient_phone   VARCHAR(30) NOT NULL,
    delivery_address  TEXT NOT NULL,
    CONSTRAINT fk_customer_orders_account
        FOREIGN KEY (account_id) REFERENCES accounts (account_id)
        ON DELETE RESTRICT
);

-- 9. Товари, кількість і ціна на момент замовлення
CREATE TABLE order_items (
    order_id    INTEGER NOT NULL,
    product_id  INTEGER NOT NULL,
    quantity    INTEGER NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(10, 2) NOT NULL CHECK (unit_price > 0),
    CONSTRAINT pk_order_items PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES customer_orders (order_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON DELETE RESTRICT
);

